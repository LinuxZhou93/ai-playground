from pptx.enum.text import PP_ALIGN
from pptx.dml.color import RGBColor

def add_slide(prs, title, content_list):
    slide_layout = prs.slide_layouts[1] # Title and Content
    slide = prs.slides.add_slide(slide_layout)
    
    # Set background color (Dark theme)
    background = slide.background
    fill = background.fill
    fill.solid()
    fill.fore_color.rgb = RGBColor(10, 25, 47) # Navy Dark

    # Title styling
    title_shape = slide.shapes.title
    title_shape.text = title
    for paragraph in title_shape.text_frame.paragraphs:
        paragraph.font.size = Pt(36)
        paragraph.font.bold = True
        paragraph.font.color.rgb = RGBColor(100, 255, 218) # Cyan Accent
        paragraph.alignment = PP_ALIGN.LEFT

    # Content styling
    body_shape = slide.shapes.placeholders[1]
    tf = body_shape.text_frame
    tf.text = ""
    for item in content_list:
        p = tf.add_paragraph()
        p.text = str(item)
        p.font.size = Pt(20)
        p.font.color.rgb = RGBColor(204, 214, 246) # Light Grey Blue
        p.space_after = Pt(10)

